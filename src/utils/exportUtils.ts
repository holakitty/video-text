import { TranscriptionResult, TranscriptSegment } from '../types/transcript';

/**
 * Format seconds to SRT timestamp: 00:01:23,456
 */
function toSrtTimestamp(seconds: number): string {
  const s = Math.max(0, seconds);
  const hrs = Math.floor(s / 3600);
  const mins = Math.floor((s % 3600) / 60);
  const secs = Math.floor(s % 60);
  const millis = Math.floor((s - Math.floor(s)) * 1000);

  return `${hrs.toString().padStart(2, '0')}:${mins.toString().padStart(2, '0')}:${secs.toString().padStart(2, '0')},${millis.toString().padStart(3, '0')}`;
}

/**
 * Format seconds to VTT timestamp: 00:01:23.456
 */
function toVttTimestamp(seconds: number): string {
  const s = Math.max(0, seconds);
  const hrs = Math.floor(s / 3600);
  const mins = Math.floor((s % 3600) / 60);
  const secs = Math.floor(s % 60);
  const millis = Math.floor((s - Math.floor(s)) * 1000);

  return `${hrs.toString().padStart(2, '0')}:${mins.toString().padStart(2, '0')}:${secs.toString().padStart(2, '0')}.${millis.toString().padStart(3, '0')}`;
}

/**
 * Convert segments to SRT string
 */
export function generateSrt(segments: TranscriptSegment[]): string {
  return segments
    .map((seg, idx) => {
      const index = idx + 1;
      const timeRange = `${toSrtTimestamp(seg.start)} --> ${toSrtTimestamp(seg.end)}`;
      const speakerTag = seg.speaker ? `<v ${seg.speaker}>${seg.text}</v>` : seg.text;
      return `${index}\n${timeRange}\n${speakerTag}\n`;
    })
    .join('\n');
}

/**
 * Convert segments to WebVTT string
 */
export function generateVtt(segments: TranscriptSegment[]): string {
  const header = 'WEBVTT - Generated by ScriptSync\n\n';
  const body = segments
    .map((seg, idx) => {
      const cueId = `cue-${idx + 1}`;
      const timeRange = `${toVttTimestamp(seg.start)} --> ${toVttTimestamp(seg.end)}`;
      const speakerText = seg.speaker ? `<v ${seg.speaker}>${seg.text}` : seg.text;
      return `${cueId}\n${timeRange}\n${speakerText}\n`;
    })
    .join('\n');
  return header + body;
}

/**
 * Convert to clean plain text
 */
export function generatePlainText(transcript: TranscriptionResult, includeTimestamps = true): string {
  if (!includeTimestamps) {
    return transcript.segments.map((s) => `${s.speaker}: ${s.text}`).join('\n\n');
  }
  return transcript.segments
    .map((s) => `[${s.startTimeFormatted} - ${s.endTimeFormatted}] ${s.speaker}:\n${s.text}`)
    .join('\n\n');
}

/**
 * Convert to Markdown notes with metadata, summary, chapters, action items
 */
export function generateMarkdown(transcript: TranscriptionResult): string {
  let md = `# ${transcript.title}\n\n`;
  md += `**Date:** ${new Date(transcript.createdAt).toLocaleDateString()} | **Duration:** ${transcript.durationFormatted} | **Words:** ${transcript.wordCount} | **Language:** ${transcript.detectedLanguage}\n\n`;

  if (transcript.summary) {
    md += `## 📌 Executive Summary\n\n${transcript.summary}\n\n`;
  }

  if (transcript.keyTakeaways && transcript.keyTakeaways.length > 0) {
    md += `## 💡 Key Takeaways\n\n`;
    transcript.keyTakeaways.forEach((k) => {
      md += `- ${k}\n`;
    });
    md += `\n`;
  }

  if (transcript.chapters && transcript.chapters.length > 0) {
    md += `## 📑 Chapters & Outline\n\n`;
    transcript.chapters.forEach((c) => {
      md += `- **[${c.startTimeFormatted}] ${c.title}** - ${c.description}\n`;
    });
    md += `\n`;
  }

  if (transcript.actionItems && transcript.actionItems.length > 0) {
    md += `## ✅ Action Items\n\n`;
    transcript.actionItems.forEach((a) => {
      const check = a.completed ? '[x]' : '[ ]';
      const ownerStr = a.owner ? ` (@${a.owner})` : '';
      const timeStr = a.timestamp ? ` [${a.timestamp}]` : '';
      md += `- ${check} ${a.task}${ownerStr}${timeStr}\n`;
    });
    md += `\n`;
  }

  md += `## 📝 Transcript\n\n`;
  transcript.segments.forEach((s) => {
    md += `### [${s.startTimeFormatted}] ${s.speaker}\n\n${s.text}\n\n`;
  });

  return md;
}

/**
 * Download a file in the browser
 */
export function downloadFile(content: string, filename: string, mimeType: string) {
  const blob = new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}
